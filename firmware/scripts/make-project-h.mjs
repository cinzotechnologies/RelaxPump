// Writes firmware/include/project.h (git-ignored) with the shared Firebase values for the build.
// The API key comes from app/google-services.json (also git-ignored).
//   node firmware/scripts/make-project-h.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const gs = new URL('../../app/google-services.json', import.meta.url);
if (!existsSync(gs)) {
  console.error('app/google-services.json not found (download it from the Firebase console).');
  process.exit(1);
}
const key = JSON.parse(readFileSync(gs, 'utf8')).client[0].api_key[0].current_key;
const out = new URL('../include/project.h', import.meta.url);
writeFileSync(
  out,
  `// Generated by firmware/scripts/make-project-h.mjs. NEVER commit.
#pragma once
#define RP_FIREBASE_API_KEY "${key}"
#define RP_FIREBASE_DB_URL  "https://iotcinzo-default-rtdb.asia-southeast1.firebasedatabase.app"
`,
);
console.log('firmware/include/project.h written');
