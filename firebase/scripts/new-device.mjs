// Factory step for one controller: creates its device account, claim hash and default data, then
// writes the board's NVS values (nvs.csv, for `npm run factory-flash`) and the box QR label into
// firebase/out/<ID>/ (git-ignored). Since v3 the per-device secrets live in NVS, not in the
// firmware (docs/two-module-system.md §4.3); secrets.h is still written as a dev fallback.
//
//   npm run new-device                                  # Household, hand-wired board (v1)
//   npm run new-device -- --type phe --board v3         # PHE module on a Rev C board
//   npm run new-device -- --id RP-3F2A9C --type household --board v2
//
//   --type   household (pump + 1–5 tanks, default) | phe (1–5 PHE lines, no pump). Set once.
//   --board  v1 = hand-wired relay module (active LOW) | v2 = PCB v2 | v3 = Rev C (8 relays)
import { createHash, randomInt } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import QRCode from 'qrcode';

import { admin, arg, DB_URL, DEVICE_DOMAIN } from './_admin.mjs';

const ALNUM = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; // no 0/O/1/I
const rand = (n, set = ALNUM) => Array.from({ length: n }, () => set[randomInt(set.length)]).join('');
const HEX = '0123456789ABCDEF';

const id = (arg('id') || `RP-${rand(6, HEX)}`).toUpperCase();
if (!/^RP-[0-9A-F]{6}$/.test(id)) throw new Error('id must look like RP-3F2A9C');
const type = arg('type', 'household');
if (type !== 'household' && type !== 'phe') throw new Error('--type must be household or phe');
const board = arg('board', 'v1');
if (!/^v[123]$/.test(board)) throw new Error('--board must be v1, v2 or v3');
const boardNum = Number(board.slice(1));
const phe = type === 'phe';
const maxTanks = 5;
const pop = rand(8);
const code = rand(12);
const password = rand(24, ALNUM + 'abcdefghjkmnpqrstuvwxyz');
const codeHash = createHash('sha256').update(`${id}:${code}`).digest('hex');
const email = `${id.toLowerCase()}@${DEVICE_DOMAIN}`;

const apiKeyFile = new URL('../../app/google-services.json', import.meta.url);
const apiKey = existsSync(apiKeyFile)
  ? JSON.parse(readFileSync(apiKeyFile, 'utf8')).client[0].api_key[0].current_key
  : 'PUT_WEB_API_KEY_HERE';

// Default layout; the owner/installer sets the real one in the app (Add device → short setup).
const config = phe
  ? { tankCount: 1, tanks: [{ emptyCm: 120, fullCm: 30 }], low: 85, high: 95 }
  : {
      tankCount: 3,
      tanks: Array.from({ length: 3 }, () => ({ emptyCm: 120, fullCm: 30 })),
      main: { enabled: false, minPct: 10 },
      low: 20,
      high: 95,
      maxRunMin: 30,
    };

const { auth, db } = admin();
const existing = await db.ref(`devices/${id}/info`).get();
if (existing.exists()) throw new Error(`${id} already exists`);

await auth.createUser({ uid: `dev-${id}`, email, password, emailVerified: true });
await db.ref().update({
  [`claims/${id}`]: { codeHash },
  [`devices/${id}/info`]: { name: phe ? 'RelaxPump PHE' : 'RelaxPump Controller', fw: '', board, maxTanks, type },
  [`devices/${id}/config`]: config,
});

const dir = new URL(`../out/${id}/`, import.meta.url);
mkdirSync(dir, { recursive: true });

// NVS values (namespace rpid: identity, src/identity.h; namespace rp: board version, src/board.cpp).
// Format: Espressif nvs_partition_gen CSV; factory-flash.mjs turns it into the 0x9000 image.
writeFileSync(
  new URL('nvs.csv', dir),
  [
    'key,type,encoding,value',
    'rpid,namespace,,',
    `id,data,string,${id}`,
    `email,data,string,${email}`,
    `pass,data,string,${password}`,
    `claim,data,string,${code}`,
    `pop,data,string,${pop}`,
    `type,data,string,${type}`,
    'rp,namespace,,',
    `board,data,i32,${boardNum}`,
    '',
  ].join('\n'),
);

// Dev fallback only: a board that was never factory-flashed (env:esp32dev, not env:release).
writeFileSync(
  new URL('secrets.h', dir),
  `// ${id} — generated by firebase/scripts/new-device.mjs. NEVER commit. Dev fallback only:
// factory boards get these values in NVS (npm run factory-flash -- --id ${id}).
#pragma once
#define RP_DEVICE_ID        "${id}"
#define RP_DEVICE_EMAIL     "${email}"
#define RP_DEVICE_PASSWORD  "${password}"
#define RP_POP              "${pop}"
#define RP_CLAIM_CODE       "${code}"
#define RP_FIREBASE_API_KEY "${apiKey}"
#define RP_FIREBASE_DB_URL  "${DB_URL}"
#define RP_BOARD            ${boardNum}
${phe ? '#define RP_TYPE_PHE\n' : ''}`,
);
writeFileSync(new URL('device.json', dir), JSON.stringify({ id, type, board, pop, code, password, apiKey }, null, 2));
const qr = `RP1;${id};${pop};${code}`;
await QRCode.toFile(fileURLToPath(new URL('qr.png', dir)), qr, { width: 600, margin: 2 });
const bleName = `RelaxPump-${phe ? 'P' : 'H'}-${id.slice(-4)}`;
writeFileSync(
  new URL('label.txt', dir),
  `RelaxPump ${phe ? 'PHE' : 'Household'} ${id}\nSetup code: ${code.replace(/(.{4})(?=.)/g, '$1-')}\nQR: ${qr}\n`,
);

console.log(`Created ${id} (${type}, board ${board})`);
console.log(`  Bluetooth name: ${bleName}`);
console.log(`  Claim code:     ${code}`);
console.log(`  Files:          firebase/out/${id}/ (nvs.csv, qr.png, label.txt, device.json, secrets.h)`);
console.log(`  Next:           npm run factory-flash -- --id ${id} --port COM5`);
process.exit(0);
