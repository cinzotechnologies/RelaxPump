// Android: app shortcuts (long-press the icon) + Google Assistant App Actions for pump control.
// Each one opens relaxpump://do/<action>; the app runs it without a tap (src/app/do/[action].tsx).
// "Hey Google, turn on the pump in RelaxPump" uses the custom intents' query patterns below.
// App Actions only work for apps installed from Google Play (test before release with the
// "Google Assistant" plugin / App Actions Test Tool in Android Studio).
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const ACTIONS = [
  {
    id: 'pump_on',
    path: 'pump-on',
    short: 'Pump on',
    long: 'Turn the pump on',
    queries: [
      'turn on the pump',
      'switch on the pump',
      'start the pump',
      'pump on',
      'fill the tank',
      'fill my tank',
    ],
  },
  {
    id: 'pump_off',
    path: 'pump-off',
    short: 'Pump off',
    long: 'Turn the pump off',
    queries: ['turn off the pump', 'switch off the pump', 'stop the pump', 'pump off'],
  },
  {
    id: 'auto_on',
    path: 'auto-on',
    short: 'Auto on',
    long: 'Turn Auto mode on',
    queries: ['turn on auto', 'turn auto on', 'start auto mode', 'auto mode on'],
  },
  {
    id: 'auto_off',
    path: 'auto-off',
    short: 'Auto off',
    long: 'Turn Auto mode off',
    queries: ['turn off auto', 'turn auto off', 'stop auto mode', 'auto mode off'],
  },
];

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/'/g, "\\'");

function shortcutsXml(pkg, scheme) {
  const cls = `${pkg}.MainActivity`;
  const intent = (a) =>
    `<intent android:action="android.intent.action.VIEW" android:targetPackage="${pkg}" android:targetClass="${cls}" android:data="${scheme}://do/${a.path}" />`;
  const caps = ACTIONS.map(
    (
      a,
    ) => `  <capability android:name="custom.actions.intent.RELAXPUMP_${a.id.toUpperCase()}" app:queryPatterns="@array/rp_${a.id}_queries">
    ${intent(a)}
  </capability>`,
  ).join('\n');
  const shortcuts = ACTIONS.map(
    (
      a,
    ) => `  <shortcut android:shortcutId="${a.id}" android:enabled="true" android:icon="@mipmap/ic_launcher" android:shortcutShortLabel="@string/rp_${a.id}_short" android:shortcutLongLabel="@string/rp_${a.id}_long">
    ${intent(a)}
  </shortcut>`,
  ).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withVoiceShortcuts.js -->
<shortcuts xmlns:android="http://schemas.android.com/apk/res/android" xmlns:app="http://schemas.android.com/apk/res-auto">
${caps}
${shortcuts}
</shortcuts>
`;
}

function valuesXml() {
  const strings = ACTIONS.map(
    (a) => `  <string name="rp_${a.id}_short">${esc(a.short)}</string>
  <string name="rp_${a.id}_long">${esc(a.long)}</string>`,
  ).join('\n');
  const arrays = ACTIONS.map(
    (a) => `  <string-array name="rp_${a.id}_queries">
${a.queries.map((q) => `    <item>${esc(q)}</item>`).join('\n')}
  </string-array>`,
  ).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withVoiceShortcuts.js -->
<resources>
${strings}
${arrays}
</resources>
`;
}

module.exports = function withVoiceShortcuts(config) {
  const pkg = config.android?.package;
  const scheme = Array.isArray(config.scheme) ? config.scheme[0] : config.scheme;
  if (!pkg || !scheme) throw new Error('withVoiceShortcuts: android.package and scheme are required');

  config = withDangerousMod(config, [
    'android',
    async (c) => {
      const res = path.join(c.modRequest.platformProjectRoot, 'app/src/main/res');
      fs.mkdirSync(path.join(res, 'xml'), { recursive: true });
      fs.mkdirSync(path.join(res, 'values'), { recursive: true });
      fs.writeFileSync(path.join(res, 'xml/shortcuts.xml'), shortcutsXml(pkg, scheme));
      fs.writeFileSync(path.join(res, 'values/relaxpump_actions.xml'), valuesXml());
      return c;
    },
  ]);

  return withAndroidManifest(config, (c) => {
    const main = AndroidConfig.Manifest.getMainActivityOrThrow(c.modResults);
    main['meta-data'] = (main['meta-data'] ?? []).filter(
      (m) => m.$['android:name'] !== 'android.app.shortcuts',
    );
    main['meta-data'].push({
      $: { 'android:name': 'android.app.shortcuts', 'android:resource': '@xml/shortcuts' },
    });
    return c;
  });
};

module.exports.ACTIONS = ACTIONS;
