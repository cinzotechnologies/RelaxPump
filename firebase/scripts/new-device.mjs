// Factory step for one controller: creates its device account, claim hash and default data,
// then writes secrets.h (for flashing) and the box QR label into firebase/out/<ID>/ (git-ignored).
//
//   npm run new-device                 # random id
//   npm run new-device -- --id RP-3F2A9C --tanks 3
import { createHash, randomInt } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import QRCode from 'qrcode';

import { admin, arg, DB_URL, DEVICE_DOMAIN } from './_admin.mjs';

const ALNUM = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; // no 0/O/1/I
const rand = (n, set = ALNUM) => Array.from({ length: n }, () => set[randomInt(set.length)]).join('');
const HEX = '0123456789ABCDEF';

const id = (arg('id') || `RP-${rand(6, HEX)}`).toUpperCase();
if (!/^RP-[0-9A-F]{6}$/.test(id)) throw new Error('id must look like RP-3F2A9C');
const maxTanks = Number(arg('tanks', '3'));
const pop = rand(8);
const code = rand(12);
const password = rand(24, ALNUM + 'abcdefghjkmnpqrstuvwxyz');
const codeHash = createHash('sha256').update(`${id}:${code}`).digest('hex');

const apiKeyFile = new URL('../../app/google-services.json', import.meta.url);
const apiKey = existsSync(apiKeyFile)
  ? JSON.parse(readFileSync(apiKeyFile, 'utf8')).client[0].api_key[0].current_key
  : 'PUT_WEB_API_KEY_HERE';

const { auth, db } = admin();
const existing = await db.ref(`devices/${id}/info`).get();
if (existing.exists()) throw new Error(`${id} already exists`);

await auth.createUser({ uid: `dev-${id}`, email: `${id.toLowerCase()}@${DEVICE_DOMAIN}`, password, emailVerified: true });
await db.ref().update({
  [`claims/${id}`]: { codeHash },
  [`devices/${id}/info`]: { name: 'RelaxPump Controller', fw: '', maxTanks },
  [`devices/${id}/config`]: {
    tankCount: maxTanks,
    low: 20,
    high: 95,
    maxRunMin: 30,
    tanks: Array.from({ length: maxTanks }, () => ({ emptyCm: 120, fullCm: 30, litres: 0 })),
  },
});

const dir = new URL(`../out/${id}/`, import.meta.url);
mkdirSync(dir, { recursive: true });
writeFileSync(
  new URL('secrets.h', dir),
  `// ${id} — generated by firebase/scripts/new-device.mjs. NEVER commit.
#pragma once
#define RP_DEVICE_ID        "${id}"
#define RP_DEVICE_EMAIL     "${id.toLowerCase()}@${DEVICE_DOMAIN}"
#define RP_DEVICE_PASSWORD  "${password}"
#define RP_POP              "${pop}"
#define RP_FIREBASE_API_KEY "${apiKey}"
#define RP_FIREBASE_DB_URL  "${DB_URL}"
`,
);
writeFileSync(new URL('device.json', dir), JSON.stringify({ id, pop, code, password, apiKey }, null, 2));
const qr = `RP1;${id};${pop};${code}`;
await QRCode.toFile(fileURLToPath(new URL('qr.png', dir)), qr, { width: 600, margin: 2 });
writeFileSync(new URL('label.txt', dir), `RelaxPump ${id}\nSetup code: ${code.replace(/(.{4})(?=.)/g, '$1-')}\nQR: ${qr}\n`);

console.log(`Created ${id}`);
console.log(`  Bluetooth name: RelaxPump-${id.slice(-4)}`);
console.log(`  Claim code:     ${code}`);
console.log(`  Files:          firebase/out/${id}/ (secrets.h, qr.png, label.txt, device.json)`);
process.exit(0);
