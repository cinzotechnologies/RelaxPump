// Writes migrations/0003_v3.sql: brings a live site to the v3 copy (docs/two-module-system.md §7).
//   npx tsx scripts/gen-v3.ts
// Content rows change only where they still hold the 0002 seed (an admin edit is kept). Products:
// the Household Controller keeps the id `kit` (existing orders), new ones are added, Pump Relay is
// hidden (the Pump Kit replaces it). 0002 stays as it was: it is already applied in production.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { DEFAULT_PRODUCTS } from '../lib/content/products';
import { toRows } from '../lib/content/sections';

const q = (s: string | null) => (s == null ? 'NULL' : `'${s.replace(/'/g, "''")}'`);
const AT = 1795305600000; // 2026-11-22, fixed so the file stays stable between runs

const seed = readFileSync(join(__dirname, '..', 'migrations', '0002_seed.sql'), 'utf8');
/** (section, key) → the JSON 0002 published. */
const old = new Map<string, string>();
for (const m of seed.matchAll(
  /^INSERT INTO content \(section, key, draft, published, updated_at\) VALUES \('([^']+)', '([^']+)', NULL, '((?:[^']|'')*)', \d+\);$/gm,
))
  old.set(`${m[1]}.${m[2]}`, m[3].replace(/''/g, "'"));
/** id → name 0002 seeded. */
const oldProducts = new Map<string, string>();
for (const m of seed.matchAll(/^INSERT INTO products \([^)]+\) VALUES \('([^']+)', '((?:[^']|'')*)',/gm))
  oldProducts.set(m[1], m[2].replace(/''/g, "'"));

const lines: string[] = [
  '-- v3: Household + PHE modules (generated by scripts/gen-v3.ts — do not edit by hand).',
  '-- Content: only rows still equal to the 0002 seed change; admin edits are kept.',
  '',
];

let changed = 0;
for (const r of toRows()) {
  const was = old.get(`${r.section}.${r.key}`);
  if (was === undefined || was === r.json) continue;
  changed++;
  lines.push(
    `UPDATE content SET published = ${q(r.json)}, updated_at = ${AT} WHERE section = ${q(r.section)} AND key = ${q(r.key)} AND published = ${q(was)};`,
  );
}
lines.push('');

DEFAULT_PRODUCTS.forEach((p, i) => {
  const sort = (i + 1) * 10;
  const was = oldProducts.get(p.id);
  if (was !== undefined) {
    // Seeded before: new name/text only while the admin has not renamed it; order + featured always
    // (visibility stays as the admin set it).
    lines.push(
      `UPDATE products SET name = ${q(p.name)}, description = ${q(p.desc)}, tag = ${q(p.tag)}, art = ${q(p.art)} WHERE id = ${q(p.id)} AND name = ${q(was)};`,
    );
    lines.push(`UPDATE products SET featured = ${p.featured ? 1 : 0}, sort = ${sort} WHERE id = ${q(p.id)};`);
  } else {
    lines.push(
      `INSERT OR IGNORE INTO products (id, name, description, category, price, tag, art, image_key, visible, featured, sort) VALUES (${q(p.id)}, ${q(p.name)}, ${q(p.desc)}, ${q(p.category)}, ${p.price ?? 'NULL'}, ${q(p.tag)}, ${q(p.art)}, NULL, 1, ${p.featured ? 1 : 0}, ${sort});`,
    );
  }
});
for (const id of oldProducts.keys())
  if (!DEFAULT_PRODUCTS.some((p) => p.id === id))
    lines.push(`UPDATE products SET visible = 0, featured = 0 WHERE id = ${q(id)};`);
lines.push('');

const out = join(__dirname, '..', 'migrations', '0003_v3.sql');
writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out}: ${changed} content rows, ${DEFAULT_PRODUCTS.length} products`);
